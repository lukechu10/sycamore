//! Components for controlling server rendering and hydration.

use sycamore_macro::{component, view};

use crate::*;

/// Component that renders its children only on the client side.
///
/// This is useful when wrapping parts of your app that are not intended to be server-side
/// rendered, e.g. highly interactive components such as graphs, etc...
#[component]
pub fn NoSsr(children: Children) -> View {
    is_ssr! {
        let _ = children;
        view! {
            no-ssr {}
        }
    }
    is_not_ssr! {
        let marker = create_node_ref();
        let view = view! {
            no-ssr(r#ref=marker)
        };
        // The initial hydration walk adopts only the placeholder. Mount the full view
        // afterward so its dynamic parts get their own anchors and effects.
        on_mount(move || {
            let marker = marker.get();
            let parent = marker.parent_node().unwrap();
            crate::node::insert_view(&parent, &children.call(), Some(&marker));
            parent.remove_child(&marker).unwrap();
        });
        view
    }
}

/// Components that do not need, or should not be hydrated on the client side.
///
/// This is useful when large parts of your app do not require client-side interactivity such as
/// static content.
///
/// However, this component will still be rendered on the client side if it is created after the
/// initial hydration phase is over, e.g. navigating to a new page with a `NoHydrate` component.
#[component]
pub fn NoHydrate(children: Children) -> View {
    if !ConstructionMode::current().is_hydrating() {
        return children.call();
    }

    is_ssr! {
        let content = provide_context_in_new_scope(ConstructionMode::Create, move || children.call());
        View::new_from_parts(smallvec::smallvec![ViewPart::OpaqueRange {
            content: Box::new(content),
        }])
    }
    is_not_ssr! {
        // The client only needs the boundary; evaluating children would claim server nodes.
        View::new_from_parts(smallvec::smallvec![ViewPart::OpaqueRange {}])
    }
}

/// Reserve a slot in `<head>` for markup generated by `cargo-sycamore`.
///
/// Place this component once in the shared server and client view when hydrating a whole
/// document. SSR emits a `<meta name="cargo-sycamore-bootstrap">` marker inside a
/// [`NoHydrate`] range. A build tool that supports this slot can insert its generated markup
/// immediately after the marker, before the closing boundary comment. Hydration leaves the
/// contents of the slot untouched. The component renders nothing in a client-only view.
///
/// This does not replace [`HydrationScript`], which records the SSR mode.
#[component]
pub fn CargoSycamoreMeta() -> View {
    is_ssr! {
        use crate::tags::HtmlMetaAttributes;

        view! {
            NoHydrate {
                meta(name="cargo-sycamore-bootstrap")
            }
        }
    }
    is_not_ssr! {
        view! { NoHydrate {} }
    }
}

/// Generate a script element for bootstrapping hydration.
///
/// In general, prefer using [`HydrationScript`] instead.
pub fn generate_hydration_script(mode: SsrMode) -> &'static str {
    match mode {
        SsrMode::Sync => "",
        SsrMode::Blocking => "window.__sycamore_ssr_mode='blocking'",
        SsrMode::Streaming => "window.__sycamore_ssr_mode='streaming'",
    }
}

/// Component that creates a script element for bootstrapping hydration. Should be rendered into
/// the `<head>` of the document.
///
/// This component is required if using SSR in blocking or streaming mode.
///
/// TODO: use this component to also capture and replay events. This requires synthetic event
/// delegation: <https://github.com/sycamore-rs/sycamore/issues/176>
#[component]
pub fn HydrationScript() -> View {
    is_ssr! {
        let mode = use_context::<SsrMode>();
        let script = generate_hydration_script(mode);
        view! {
            NoHydrate {
                script(dangerously_set_inner_html=script)
            }
        }
    }
    is_not_ssr! {
        view! { NoHydrate {} }
    }
}
